"""
AgentPrahari JSON Structure Enforcer and Auto-Repair Guard.
Ensures model output is valid JSON, strips markdown fences, fixes trailing commas, and validates against schemas.
"""

from __future__ import annotations
import json
import re
from typing import Any, Dict, List, Optional, Tuple
from agentprahari.core.config import PrahariConfig
from agentprahari.core.result import GuardCategory, Severity, Violation
from agentprahari.output_guards.base import BaseOutputGuard


class JSONEnforcerGuard(BaseOutputGuard):
    """
    Validates, extracts, and auto-repairs JSON output generated by LLMs.
    """

    @property
    def name(self) -> str:
        return "JSONEnforcerGuard"

    def _extract_and_repair(self, text: str) -> Tuple[Optional[str], Optional[Any]]:
        """Extracts JSON substring and applies heuristic repairs for common LLM syntax flaws."""
        raw = text.strip()

        # 1. Strip markdown code fences if present (```json ... ```)
        fence_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", raw, re.IGNORECASE)
        if fence_match:
            candidate = fence_match.group(1).strip()
        else:
            # Find first { or [ and last } or ]
            start_brace = raw.find("{")
            start_bracket = raw.find("[")

            if start_brace != -1 and (start_bracket == -1 or start_brace < start_bracket):
                end_brace = raw.rfind("}")
                candidate = raw[start_brace : end_brace + 1] if end_brace != -1 else raw[start_brace:]
            elif start_bracket != -1:
                end_bracket = raw.rfind("]")
                candidate = raw[start_bracket : end_bracket + 1] if end_bracket != -1 else raw[start_bracket:]
            else:
                candidate = raw

        # Try direct parse
        try:
            parsed = json.loads(candidate)
            return json.dumps(parsed, indent=2), parsed
        except json.JSONDecodeError:
            pass

        # Apply heuristic repairs:
        repaired = candidate

        # Remove trailing commas before } or ]
        repaired = re.sub(r",\s*([}\]])", r"\1", repaired)

        # Replace single quotes with double quotes for valid JSON
        # Handles keys and string values cleanly
        repaired = re.sub(r"\'([^\'\\]*)\'", r'"\1"', repaired)

        # Try parse again
        try:
            parsed = json.loads(repaired)
            return json.dumps(parsed, indent=2), parsed
        except json.JSONDecodeError:
            return None, None

    def evaluate(
        self,
        output_text: str,
        config: PrahariConfig
    ) -> Tuple[str, List[Violation]]:
        if not config.enforce_json:
            return output_text, []

        repaired_str, parsed_obj = self._extract_and_repair(output_text)
        violations: List[Violation] = []

        if parsed_obj is None:
            violations.append(Violation(
                rule_id="OUT_INVALID_JSON",
                message="Model failed to produce valid parseable JSON output",
                severity=Severity.HIGH,
                category=GuardCategory.OUTPUT,
                guard_name=self.name,
                matched_content=output_text[:100],
                details={"enforce_json": True}
            ))
            return output_text, violations

        # Optional schema validation
        if config.json_schema and isinstance(config.json_schema, dict):
            required_keys = config.json_schema.get("required", [])
            if isinstance(parsed_obj, dict):
                missing = [k for k in required_keys if k not in parsed_obj]
                if missing:
                    violations.append(Violation(
                        rule_id="OUT_JSON_SCHEMA_MISSING_KEYS",
                        message=f"JSON output missing required keys: {missing}",
                        severity=Severity.HIGH,
                        category=GuardCategory.OUTPUT,
                        guard_name=self.name,
                        matched_content=None,
                        details={"missing_keys": missing}
                    ))

        return repaired_str, violations
